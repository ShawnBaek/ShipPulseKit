#!/bin/bash
# Regenerates Sources/ShipPulseKit/MetricKitSymbols.swift from what the SDK really references.
#
# Builds the SDK for every platform and Simulator in Debug and Release, finds the symbols its
# object files import from MetricKit and StateReporting, and fails if any of them isn't weak.
# Device and Simulator lists are separate because their SDKs differ: the device mxSignpost
# inlines a call to _MXSignpostMetricsSnapshot, which the Simulator doesn't have.
#
#   scripts/update-metrickit-symbols.sh           rewrites the file
#   scripts/update-metrickit-symbols.sh --check   fails if the file is out of date
set -euo pipefail

cd "$(dirname "$0")/.."
output=Sources/ShipPulseKit/MetricKitSymbols.swift
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

exports() { # SDK name, framework: every symbol its text stub declares, one per line
    local stub
    stub="$(xcrun --sdk "$1" --show-sdk-path)/System/Library/Frameworks/$2.framework/$2.tbd"
    if [ ! -f "$stub" ]; then
        case "$1/$2" in
        watch*/MetricKit) return 0 ;; # MetricKit doesn't exist on watchOS.
        esac
        echo "error: no text stub at $stub, so its imports can't be identified." >&2
        exit 1
    fi
    # Stubs list Objective-C classes by bare name. The extra lines for other words are harmless,
    # because the result is only intersected with real imports.
    tr -s " ,'[]\t" '\n' <"$stub" |
        awk '/^_/ { print; next } { print "_OBJC_CLASS_$_" $0; print "_OBJC_METACLASS_$_" $0 }' |
        LC_ALL=C sort -u
}

collect() { # label, destination platform, products-directory suffix, SDK name
    local platform=$1 destination=$2 suffix=$3 sdk=$4 configuration object
    for configuration in Debug Release; do
        xcodebuild build -scheme ShipPulseKit -configuration "$configuration" \
            -destination "generic/platform=$destination" -derivedDataPath "$work/dd" \
            CODE_SIGNING_ALLOWED=NO -quiet >"$work/build.log" 2>&1 || { cat "$work/build.log"; exit 1; }
        object="$work/dd/Build/Products/$configuration$suffix/ShipPulseKit.o"
        nm -um "$object" >>"$work/$platform.imports"
    done
    # A symbol's name doesn't say which framework it's from (mxSignpost inlines a call to
    # _MXSignpostMetricsSnapshot), so match the imports against what each framework exports.
    exports "$sdk" MetricKit >"$work/$platform.mk.exports"
    exports "$sdk" StateReporting >"$work/$platform.sr.exports"
    # Fields are "(undefined) [weak] external <symbol>", possibly with a trailing "(from ...)".
    awk '{ for (i = 1; i < NF; i++) if ($i == "external") { print $(i + 1), ($2 == "weak" ? "weak" : "strong") } }' \
        "$work/$platform.imports" | LC_ALL=C sort -u >"$work/$platform.imports.parsed"
    local list
    for list in mk sr; do
        awk 'NR == FNR { exported[$1] = 1; next } $1 in exported' \
            "$work/$platform.$list.exports" "$work/$platform.imports.parsed" >"$work/$platform.$list.parsed"
        if grep ' strong$' "$work/$platform.$list.parsed"; then
            echo "error: the symbols above are strongly linked on $platform. Every MetricKit and StateReporting import must be @_weakLinked." >&2
            exit 1
        fi
        # dlsym takes the C name, without the linker's leading underscore.
        awk '{print $1}' "$work/$platform.$list.parsed" | sed 's/^_//' | LC_ALL=C sort -u >"$work/$platform.$list"
    done
}

emit() { # constant name, symbols file
    if [ -s "$2" ]; then
        printf '    static let %s: [String] = [\n' "$1"
        sed 's/.*/        "&",/' "$2"
        printf '    ]\n'
    else
        printf '    static let %s: [String] = []\n' "$1"
    fi
}

emit_platform() { # platform
    echo '    #if targetEnvironment(simulator)'
    emit metricKit "$work/$1Simulator.mk"
    emit stateReporting "$work/$1Simulator.sr"
    echo '    #else'
    emit metricKit "$work/$1.mk"
    emit stateReporting "$work/$1.sr"
    echo '    #endif'
}

collect iOS iOS -iphoneos iphoneos
collect iOSSimulator "iOS Simulator" -iphonesimulator iphonesimulator
collect macOS macOS "" macosx
collect Catalyst "macOS,variant=Mac Catalyst" -maccatalyst macosx
collect visionOS visionOS -xros xros
collect visionOSSimulator "visionOS Simulator" -xrsimulator xrsimulator
collect watchOS watchOS -watchos watchos
collect watchOSSimulator "watchOS Simulator" -watchsimulator watchsimulator

for platform in macOS Catalyst; do
    if ! cmp -s "$work/iOS.mk" "$work/$platform.mk" || ! cmp -s "$work/iOS.sr" "$work/$platform.sr"; then
        diff "$work/iOS.mk" "$work/$platform.mk" >&2 || true
        diff "$work/iOS.sr" "$work/$platform.sr" >&2 || true
        echo "error: iOS and $platform reference different symbols. Teach this script a separate $platform branch." >&2
        exit 1
    fi
done

{
    echo '// Generated by scripts/update-metrickit-symbols.sh. Do not edit.'
    echo
    echo '/// Every MetricKit and StateReporting symbol this SDK references, as C names for `dlsym`.'
    echo '///'
    echo '/// ``MetricKitSupport`` turns the SDK off unless all of them exist, because each one is'
    echo '/// weak-linked and a call through a missing one jumps to null.'
    echo 'enum MetricKitSymbols {'
    echo '    #if os(watchOS)'
    emit_platform watchOS
    echo '    #elseif os(visionOS)'
    emit_platform visionOS
    echo '    #else'
    emit_platform iOS
    echo '    #endif'
    echo '}'
} >"$work/generated.swift"

if [ "${1:-}" = "--check" ]; then
    if ! diff -u "$output" "$work/generated.swift"; then
        echo "error: $output is out of date. Run scripts/update-metrickit-symbols.sh." >&2
        exit 1
    fi
    echo "$output is up to date; every symbol is weak."
else
    cp "$work/generated.swift" "$output"
    echo "Wrote $output; every symbol is weak."
fi
